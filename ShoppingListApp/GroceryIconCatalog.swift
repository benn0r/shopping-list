  static func imageName(for label: String) -> String? {
    let normalized = normalize(label)
    guard !normalized.isEmpty else { return nil }
    let padded = " \(normalized) "
    return aliases.first { padded.contains(" \($0.phrase) ") }?.imageName
  }

  private static func normalize(_ value: String) -> String {
    let folded = value.folding(
      options: [.diacriticInsensitive, .caseInsensitive], locale: .current
    ).lowercased()
    let ascii = folded.unicodeScalars.map { scalar -> Character in
      let value = scalar.value
      return (value >= 97 && value <= 122) || (value >= 48 && value <= 57)
        ? Character(String(scalar)) : " "
    }
    return String(ascii).split(whereSeparator: { $0 == " " }).joined(separator: " ")
  }
