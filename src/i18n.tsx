export function translate(language: AppLanguage, key: Key, values: Record<string, string> = {}) {
  const source = refinements[language]?.[key] || translations[language][key];
  return Object.entries(values).reduce(
    (text, [name, replacement]) => text.replaceAll(`{${name}}`, replacement),
    source,
  );
}
export function I18nProvider({ children }: PropsWithChildren) {
  const [language, setCurrentLanguage] = useState<AppLanguage>('en');
  useEffect(() => {
    loadAppLanguage()
      .then(setCurrentLanguage)
      .catch(() => {});
  }, []);
  const value = useMemo<I18nValue>(
    () => ({
      language,
      setLanguage: async (next) => {
        setCurrentLanguage(next);
        await saveAppLanguage(next);
      },
      t: (key, values) => translate(language, key, values),
    }),
    [language],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}
export function useI18n() {
  return useContext(I18nContext);
}
