function normalize(value: string) {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLocaleLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

const aliases = rules
  .flatMap(([icon, words]) => words.split('|').map((word) => ({ icon, word: normalize(word) })))
  .sort((left, right) => right.word.length - left.word.length);

export function groceryIconForLabel(label: string): ImageSourcePropType | undefined {
  const normalized = normalize(label);
  if (!normalized) return undefined;
  const padded = ` ${normalized} `;
  const match = aliases.find(({ word }) => padded.includes(` ${word} `));
  return match ? icons[match.icon] : undefined;
}
